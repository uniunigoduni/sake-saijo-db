def clean_rice(v):
    s = "" if pd.isna(v) else str(v).strip()
    if not s:
        return ""
    s = re.split(r"\s*(?:精米歩合|日本酒度|酸度|アミノ酸度|アルコール|alc度数|酵母|酒母|製法|仕様|おすすめ|飲み方|拡大表示|購入数|●)\s*[:：]?", s, maxsplit=1)[0]
    return s.strip(" ・/")


