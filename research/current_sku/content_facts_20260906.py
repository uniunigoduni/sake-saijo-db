def newrow(df, spec):
    row = {c:"" for c in df.columns}
    row.update(dict(
        酒蔵=spec["酒蔵"], ブランド=spec["ブランド"], シリーズ="", ブランド優先度="C", ブランド位置づけ="",
        商品名=spec["商品名"], 分類=spec["分類"], 甘辛目安="不明", 甘辛判定根拠="公開情報で判定材料不足",
        おすすめの飲み方="要確認", 飲み方情報="公開情報で要確認", 流通区分=spec.get("流通区分","限定流通"),
        備考="2026-09-06現行性を公式情報で再確認", 出典URL=spec["出典URL"], 出典数=1,
    ))
    row.update({k:v for k,v in spec.items() if k in row})
    row.update({k:v for k,v in OV.get((spec["酒蔵"],spec["商品名"]),{}).items() if k in row})
    return row


def apply(products):
    for area, df in list(products.items()):
        df = df.copy().fillna("")
        collab = df["商品名"].astype(str).str.contains("龍が如く|サンフレ|無相 SAKE MUSOU", regex=True, na=False)
        df = df.loc[~collab].copy()
        df["使用米"] = df["使用米"].map(clean_rice)
        for (brewery, product), facts in OV.items():
            mask = (df["酒蔵"] == brewery) & (df["商品名"] == product)
            if mask.any():
                for col, val in facts.items():
                    if col in df.columns:
                        df.loc[mask, col] = val
        for spec in ADD:
            if spec["酒蔵"] not in set(df["酒蔵"]):
                continue
            mask = (df["酒蔵"] == spec["酒蔵"]) & (df["商品名"] == spec["商品名"])
            if mask.any():
                for col, val in spec.items():
                    if col in df.columns and col not in ("酒蔵", "商品名"):
                        df.loc[mask, col] = val
            else:
                df = pd.concat([df, pd.DataFrame([newrow(df, spec)])], ignore_index=True)
        df["使用米"] = df["使用米"].map(clean_rice)
        products[area] = df.reset_index(drop=True)
        products[area].to_csv(DIR / f"boss_{area}_products.csv", index=False, encoding="utf-8-sig")

    p = DIR / "boss_export_summary.json"
    if p.exists():
        summary = json.loads(p.read_text(encoding="utf-8"))
        for area, df in products.items():
            summary[area]["products"] = len(df)
            summary[area]["by_brewery"] = df["酒蔵"].value_counts().to_dict()
        p.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    return products

