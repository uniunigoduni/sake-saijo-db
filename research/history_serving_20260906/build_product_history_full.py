def individual_history(r):
    key=(r['酒蔵'],r['商品名']); desc=clean(r.get('page_description',''))
    if key in CURATED:
        return CURATED[key],'個別沿革確認'
    facts=historical_signals(desc)
    awards=award_fact(desc)
    if awards:
        facts.append('、'.join(awards)+'の実績が商品ページに記録されている')
    pub=clean(r.get('page_published',''))[:10]
    if pub:
        facts.insert(0,f'少なくとも{pub}には現行流通ページで商品単位の取扱いが確認できる')
    facts += positioning(r,desc)[:2]
    facts += technical(r,desc)[:1]
    facts += context_facts(r,desc)[:1]
    src='公式商品ページ' if official(r.get('出典URL','')) else '現行の流通・商品ページ'
    base=specs(r)
    snapshot=(f'{TODAY}時点で{src}に現行品として掲載され、{base}の設計で展開されている' if base else f'{TODAY}時点で{src}に商品単位で掲載され、現行ラインの独立商品として流通している')
    if not facts: facts=[snapshot]
    elif len(facts)<2: facts.append(snapshot)
    text='。'.join(f.rstrip('。') for f in facts[:3] if f)+ '。'
    if len(text)<60 and snapshot.rstrip('。') not in text:
        text=text.rstrip('。')+'。'+snapshot.rstrip('。')+'。'
    return text,('商品ページ沿革' if historical_signals(desc) or awards or pub else '現行商品位置づけ')

