def clean(s): return re.sub(r'\s+',' ',str(s or '')).strip()
def official(url): return any(d in str(url) for d in OFFICIAL_DOMAINS)
def specs(r):
    bits=[]
    cat=clean(r.get('分類','')); rice=clean(r.get('使用米','')); polish=clean(r.get('精米歩合',''))
    if cat and cat not in ('その他','要確認','不明'): bits.append(cat)
    if rice and len(rice)<=35 and not re.search(r'旨味|味わい|香り|おすすめ|お酒|料理',rice): bits.append('使用米 '+rice)
    if polish and len(polish)<=20: bits.append('精米歩合 '+polish)
    return '、'.join(bits[:3])
def variant(name):
    tags=[]
    for k in ['生酒','生原酒','原酒','おりがらみ','うすにごり','にごり','ひやおろし','秋あがり','生酛','しぼりたて','あらばしり','袋吊り','凍結','低アルコール']:
        if k in name and k not in tags: tags.append(k)
    return '・'.join(tags)
