def historical_signals(desc):
    facts=[]
    m=re.search(r'発売以来\s*([0-9０-９]+)年',desc)
    if m: facts.append(f'発売以来約{m.group(1)}年続くロングセラーとして案内されている')
    m=re.search(r'([0-9０-９]+)年以上にわたって愛され',desc)
    if m: facts.append(f'{m.group(1)}年以上続くロングセラーとして案内されている')
    if '1980年代' in desc and '開発' in desc: facts.append('1980年代に先代が開発した商品を改良しながら継承している')
    if '2013年' in desc and 'ハイブリッド' in desc: facts.append('2013年に開発したハイブリッド酒母の技術を商品化している')
    if '2021BY' in desc and '原形精米' in desc: facts.append('2021BYから原料米の一部に原形精米（真吟）を導入した')
    if '2022BY' in desc and '乳酸菌' in desc: facts.append('2022BYから生酛由来の選抜乳酸菌を使う設計へ発展した')
    if '1年に1回' in desc: facts.append('年1回の限定発売として継続展開される')
    return facts

def award_fact(desc):
    hits=[]
    for m in re.finditer(r'((?:19|20)\d{2}年[^。]{0,90}?(?:金賞|最高金賞|大賞|プラチナ|SILVER|BRONZE|シルバー|メダル|受賞))',desc):
        s=clean(m.group(1)).replace('🎖️','')
        if len(s)<=110 and s not in hits: hits.append(s)
        if len(hits)>=2: break
    return hits
def positioning(r,desc):
    name=str(r['商品名']); parts=[]
    if 'フラッグシップ' in desc: parts.append('蔵がフラッグシップと位置づける')
    elif '代表する' in desc or '代表的' in desc: parts.append('蔵の代表商品として位置づけられる')
    elif '人気NO.1' in desc or '一番人気' in desc: parts.append('人気商品として案内される')
    dist=str(r.get('流通区分',''))
    if '輸出' in dist or '輸出' in name: parts.append('輸出向けに展開される')
    elif '蔵元' in dist or '酒蔵限定' in name or '蔵元限定' in desc: parts.append('蔵元限定で展開される')
    elif '限定' in dist or '限定' in name or '限定' in desc: parts.append('限定商品として展開される')
    elif any(x in name for x in ('ひやおろし','秋あがり','しぼりたて','夏','青冴え')): parts.append('季節商品として展開される')
    v=variant(name)
    if v: parts.append(f'{v}という仕立てで通常品と区別される')
    return parts

